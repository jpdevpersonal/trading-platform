import { expect, test } from "@playwright/test";

test("real HTTP and PostgreSQL import, repeat, reload, upstream failure and recovery", async ({ page }) => {
  const imports: string[] = [];
  page.on("request", (request) => {
    if (request.method() === "POST") imports.push(request.url());
    expect(request.url()).not.toContain("api.massive.com");
    expect(request.headers()).not.toHaveProperty("authorization");
  });
  await page.goto("/");
  const link = page.getByRole("link", { name: "Price history", exact: true });
  await link.focus();
  await expect(link).toHaveCSS("outline-style", "solid");
  await page.keyboard.press("Enter");
  await expect(page.getByRole("heading", { name: "Price history", exact: true })).toBeVisible();
  await expect(page.getByLabel("Listing")).toContainText("S-00 · XAAA · USD · Sample");
  await page.getByRole("button", { name: "Next listings" }).click();
  await expect(page.getByLabel("Listing")).toContainText("AAPL · XNAS · USD");
  await page.getByLabel("Listing").selectOption("20000000-0000-0000-0000-000000000001");
  await page.getByLabel("From (inclusive)").fill("2026-11-23");
  await page.getByLabel("To (inclusive)").fill("2026-11-24");
  await expect(page.getByText("No imports yet.", { exact: false })).toBeVisible();
  expect(imports).toHaveLength(0);
  const button = page.getByRole("button", { name: "Import daily prices" });
  await button.focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("status")).toHaveText("Import complete: 2 inserted, 0 updated, 0 unchanged.");
  const table = page.getByRole("table");
  await expect(table.getByRole("row")).toHaveCount(3);
  await expect(table.getByRole("rowheader")).toHaveText(["2026-11-24", "2026-11-23"]);
  await expect(page.getByText("Massive · Unadjusted daily prices", { exact: true })).toBeVisible();
  await expect(page.getByText("Quote currency: USD")).toBeVisible();
  await expect(page.getByText("Latest trading date in this view: 2026-11-24")).toBeVisible();
  await expect(page.getByText(/Last successful refresh for this stock:.*Z \(UTC\), range 2026-11-23 to 2026-11-24/)).toBeVisible();
  const rows = await table.innerText();
  await button.click();
  await expect(page.getByRole("status")).toHaveText("Import complete: 0 inserted, 0 updated, 2 unchanged.");
  await expect(button).toBeEnabled();
  expect(await table.innerText()).toBe(rows);
  const url = page.url();
  await page.reload();
  await expect(table).toBeVisible();
  expect(page.url()).toBe(url);
  expect(await table.innerText()).toBe(rows);
  expect(imports).toHaveLength(2);
  await button.click();
  await expect(page.getByRole("main").getByRole("alert")).toContainText("Massive returned an invalid or incomplete");
  expect(await table.innerText()).toBe(rows);
  await button.click();
  await expect(page.getByRole("status")).toHaveText("Import complete: 0 inserted, 0 updated, 2 unchanged.");
  await page.setViewportSize({ width: 360, height: 800 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(table).toBeVisible();
});
